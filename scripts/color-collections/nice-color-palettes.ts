// Generates src/foundation/color-palette/collections/nice-color-palettes/index.ts from
// nice-color-palettes-colors.json and nice-color-palettes-palettes.json: a selection of 40 palettes
// from the package's 100.json and the colors they use. Palettes have no names in the package, so
// each is numbered by its place in 100.json. Usage:
// npx vite-node scripts/color-collections/nice-color-palettes.ts -- <source dir> [order.json]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GROUP_NAMES, familyOf, orderColors, orderNote, quote, savedOrder } from './order.ts';

const [source, orderFile] = process.argv.slice(2).filter((arg) => arg !== '--');
if (!source) throw new Error('usage: nice-color-palettes.ts <source dir> [order.json]');
const read = (file: string) => JSON.parse(readFileSync(join(source, file), 'utf8'));
const data = read('nice-color-palettes-palettes.json') as {
  source_revision: string;
  palettes: { source_index_1based: number; colors: string[] }[];
};
const palettes = data.palettes;
const order = savedOrder('nice-color-palettes', orderFile);
const colors = orderColors(
  (read('nice-color-palettes-colors.json').colors as { hex: string }[]).map((color) =>
    color.hex.toLowerCase(),
  ),
  (value) => value,
  order,
);
const listed = new Set(colors);
for (const palette of palettes)
  for (const hex of palette.colors)
    if (!listed.has(hex.toLowerCase()))
      throw new Error(`palette ${palette.source_index_1based}: ${hex} is not listed`);
const used = new Set(colors.map(familyOf));
const out = `import type { ColorCollection } from '../../types.js';

/**
 * A selection of ${palettes.length} palettes from the nice-color-palettes package (its 100.json at revision
 * ${data.source_revision.slice(0, 7)}) and the ${colors.length} colors they use, grouped by hue family and
 * ${orderNote(order)}.
 * Palettes have no names in the package, so each is numbered by its place in 100.json; colors and
 * their order within a palette are the package's. MIT License (LICENSE beside this file).
 *
 * Generated by scripts/color-collections/nice-color-palettes.ts.
 */
const niceColorPalettes: ColorCollection = {
  id: 'nice-color-palettes',
  name: 'Nice Color Palettes',
  description:
    'A selection of ${palettes.length} five-color palettes from the nice-color-palettes package and the ${colors.length} colors they use.',
  attribution: [
    {
      name: 'nice-color-palettes',
      url: 'https://github.com/Experience-Monks/nice-color-palettes',
      license: 'MIT',
    },
  ],
  groups: [
${Object.entries(GROUP_NAMES)
  .filter(([id]) => used.has(id))
  .map(([id, name]) => `    { id: ${quote(id)}, name: ${quote(name)} },`)
  .join('\n')}
  ],
  colors: [
${colors.map((value) => `    { value: ${quote(value)}, group: ${quote(familyOf(value))} },`).join('\n')}
  ],
  palettes: [
${palettes
  .map(
    (palette) =>
      `    { name: ${quote(`Palette ${palette.source_index_1based}`)}, colors: [${palette.colors.map((hex) => quote(hex.toLowerCase())).join(', ')}] },`,
  )
  .join('\n')}
  ],
};

export default niceColorPalettes;
export { niceColorPalettes };
`;
writeFileSync('src/foundation/color-palette/collections/nice-color-palettes/index.ts', out);
console.log(colors.length, 'colors', palettes.length, 'palettes');
