// Generates src/foundation/color-palette/collections/wes-anderson/index.ts from the wesanderson
// package export (wes-anderson-palettes.json): its discrete palettes and the colors they use. The
// Rushmore alias and the Zissou1Continuous scale helper are left out. Usage:
// npx vite-node scripts/color-collections/wes-anderson.ts -- <source dir> [order.json]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GROUP_NAMES, familyOf, orderColors, orderNote, quote, savedOrder } from './order.ts';

const [source, orderFile] = process.argv.slice(2).filter((arg) => arg !== '--');
if (!source) throw new Error('usage: wes-anderson.ts <source dir> [order.json]');
const palettes = (
  JSON.parse(readFileSync(join(source, 'wes-anderson-palettes.json'), 'utf8')).palettes as {
    name: string;
    colors: string[];
    kind: string;
  }[]
).filter((palette) => palette.kind === 'discrete_palette');
const order = savedOrder('wes-anderson', orderFile);
const colors = orderColors(
  [...new Set(palettes.flatMap((palette) => palette.colors.map((hex) => hex.toLowerCase())))],
  (value) => value,
  order,
);
const used = new Set(colors.map(familyOf));
const out = `import type { ColorCollection } from '../../types.js';

/**
 * The palettes of the wesanderson package by Karthik Ram and contributors: its ${palettes.length} discrete
 * palettes, inspired by Wes Anderson's films, and the ${colors.length} colors they use, grouped by hue
 * family and
 * ${orderNote(order)}.
 * Community selections, not by Wes Anderson. Colors have no names in the package. Palette names
 * and color order are the package's; the Rushmore alias and the Zissou1Continuous scale helper are
 * left out. MIT License (LICENSE beside this file).
 *
 * Generated by scripts/color-collections/wes-anderson.ts.
 */
const wesAnderson: ColorCollection = {
  id: 'wes-anderson',
  name: 'Wes Anderson palettes',
  description:
    "Film-inspired palettes from Karthik Ram's wesanderson package: ${palettes.length} palettes and the ${colors.length} colors they use. Community selections, not by Wes Anderson.",
  attribution: [
    { name: 'wesanderson', url: 'https://github.com/karthik/wesanderson', license: 'MIT' },
  ],
  groups: [
${Object.entries(GROUP_NAMES)
  .filter(([id]) => used.has(id))
  .map(([id, name]) => `    { id: ${quote(id)}, name: ${quote(name)} },`)
  .join('\n')}
  ],
  colors: [
${colors.map((value) => `    { value: ${quote(value)}, group: ${quote(familyOf(value))} },`).join('\n')}
  ],
  palettes: [
${palettes
  .map(
    (palette) =>
      `    { name: ${quote(palette.name)}, colors: [${palette.colors.map((hex) => quote(hex.toLowerCase())).join(', ')}] },`,
  )
  .join('\n')}
  ],
};

export default wesAnderson;
export { wesAnderson };
`;
writeFileSync('src/foundation/color-palette/collections/wes-anderson/index.ts', out);
console.log(colors.length, 'colors', palettes.length, 'palettes');
