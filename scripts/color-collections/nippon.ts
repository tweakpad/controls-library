// Generates src/foundation/color-palette/collections/nippon/index.ts from nippon-colors.json.
// Usage: npx vite-node scripts/color-collections/nippon.ts -- <source dir> [order.json], where
// order.json is a `{ collection, order }` copied from the collection-order fixture.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GROUP_NAMES, familyOf, orderColors, orderNote, quote, savedOrder } from './order.ts';

const [source, orderFile] = process.argv.slice(2).filter((arg) => arg !== '--');
if (!source) throw new Error('usage: nippon.ts <source dir> [order.json]');
const data = JSON.parse(readFileSync(join(source, 'nippon-colors.json'), 'utf8'));
const entries: { slug: string; hex: string }[] = data.colors;
const order = savedOrder('nippon', orderFile);

// The name is the slug with only its first letter capitalized: nadeshiko → Nadeshiko.
const colors = orderColors(
  entries.map((entry) => ({
    value: entry.hex.toLowerCase(),
    name: entry.slug.charAt(0).toUpperCase() + entry.slug.slice(1),
  })),
  (color) => color.value,
  order,
);
const used = new Set(colors.map((color) => familyOf(color.value)));
const out = `import type { ColorCollection } from '../../types.js';

/**
 * The traditional colors of Japan as collected by Ono Takehiko on Nippon Colors: ${colors.length} colors
 * named after their romanized names (the slug with its first letter capitalized), grouped by hue
 * family and ${orderNote(order)}. Values are the site's
 * published HEX, retrieved on ${data.metadata.retrieved_on}. No palettes are published.
 *
 * Generated by scripts/color-collections/nippon.ts.
 */
const nipponColors: ColorCollection = {
  id: 'nippon',
  name: 'Nippon Colors',
  description: 'The ${colors.length} traditional colors of Japan collected by Ono Takehiko, named after their romanized names.',
  attribution: [{ name: 'Nippon Colors', url: 'https://nipponcolors.com/' }],
  groups: [
${Object.entries(GROUP_NAMES)
  .filter(([id]) => used.has(id))
  .map(([id, name]) => `    { id: ${quote(id)}, name: ${quote(name)} },`)
  .join('\n')}
  ],
  colors: [
${colors
  .map(
    (color) =>
      `    { value: ${quote(color.value)}, name: ${quote(color.name)}, group: ${quote(familyOf(color.value))} },`,
  )
  .join('\n')}
  ],
};

export default nipponColors;
export { nipponColors };
`;
writeFileSync('src/foundation/color-palette/collections/nippon/index.ts', out);
console.log(colors.length, 'colors');
