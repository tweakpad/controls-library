// Generates src/foundation/color-palette/collections/le-corbusier/index.ts from
// le-corbusier-colors.json (the 63 colors), le-corbusier-palettes.json (the selections derived
// from the 1931 keyboards) and le-corbusier-keyboards.json (the keyboard names). Usage:
// npx vite-node scripts/color-collections/le-corbusier.ts -- <source dir> [order.json]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GROUP_NAMES, familyOf, orderColors, orderNote, quote, savedOrder } from './order.ts';

const [source, orderFile] = process.argv.slice(2).filter((arg) => arg !== '--');
if (!source) throw new Error('usage: le-corbusier.ts <source dir> [order.json]');
const read = (file: string) => JSON.parse(readFileSync(join(source, file), 'utf8'));
const catalog: { name: string; hex: string }[] = read('le-corbusier-colors.json').colors;
const palettes: {
  colors: string[];
  selections: { keyboard_id: string; accent_start: number; accent_count: number }[];
}[] = read('le-corbusier-palettes.json').palettes;
const keyboards: { id: string; name: string }[] = read('le-corbusier-keyboards.json').keyboards;
const order = savedOrder('le-corbusier', orderFile);

// Each keyboard name has two configurations (two background pairs): A and B, in file order.
const keyboardLabel = new Map<string, string>();
const seen = new Map<string, number>();
for (const keyboard of keyboards) {
  const index = seen.get(keyboard.name) ?? 0;
  seen.set(keyboard.name, index + 1);
  keyboardLabel.set(keyboard.id, `${keyboard.name} ${String.fromCharCode(65 + index)}`);
}
// A selection is named after its first originating keyboard and accent window: Espace I A, 1–3.
const paletteName = (palette: (typeof palettes)[number]): string => {
  const first = palette.selections[0]!;
  const end = first.accent_start + first.accent_count - 1;
  const window = end === first.accent_start ? `${end}` : `${first.accent_start}–${end}`;
  return `${keyboardLabel.get(first.keyboard_id)}, ${window}`;
};

const colors = orderColors(
  catalog.map((color) => ({
    value: color.hex.toLowerCase(),
    name: color.name.charAt(0).toUpperCase() + color.name.slice(1),
  })),
  (color) => color.value,
  order,
);
const used = new Set(colors.map((color) => familyOf(color.value)));
const out = `import type { ColorCollection } from '../../types.js';

/**
 * Le Corbusier's Polychromie Architecturale: the ${colors.length} colors of 1931 and 1959 with their French
 * names (first letter capitalized), grouped by hue family and
 * ${orderNote(order)}, and as palettes the ${palettes.length}
 * selections derived from the 1931 color keyboards: each run of one to three neighbouring accents
 * with the keyboard's two background colors, named after the keyboard and the accents. These are
 * enumerated from the keyboards, not compositions by Le Corbusier. Values are the screen RGB of the
 * official Les Couleurs Suisse catalog, not paint specifications.
 *
 * Generated by scripts/color-collections/le-corbusier.ts.
 */
const leCorbusier: ColorCollection = {
  id: 'le-corbusier',
  name: 'Le Corbusier',
  description:
    "Le Corbusier's Polychromie Architecturale: ${colors.length} colors, with ${palettes.length} selections from his 1931 color keyboards as palettes.",
  attribution: [
    { name: 'Les Couleurs Suisse', url: 'https://dz.lescouleurs.ch/fr/les-couleurs/63-couleurs/' },
  ],
  groups: [
${Object.entries(GROUP_NAMES)
  .filter(([id]) => used.has(id))
  .map(([id, name]) => `    { id: ${quote(id)}, name: ${quote(name)} },`)
  .join('\n')}
  ],
  colors: [
${colors
  .map(
    (color) =>
      `    { value: ${quote(color.value)}, name: ${quote(color.name)}, group: ${quote(familyOf(color.value))} },`,
  )
  .join('\n')}
  ],
  palettes: [
${palettes
  .map(
    (palette) =>
      `    { name: ${quote(paletteName(palette))}, colors: [${palette.colors.map((hex) => quote(hex.toLowerCase())).join(', ')}] },`,
  )
  .join('\n')}
  ],
};

export default leCorbusier;
export { leCorbusier };
`;
writeFileSync('src/foundation/color-palette/collections/le-corbusier/index.ts', out);
console.log(colors.length, 'colors', palettes.length, 'palettes');
