// Generates src/foundation/color-palette/collections/riso/index.ts from riso-palette.json (inks)
// and riso-club-palettes.json (Riso Club combinations). Usage:
// npx vite-node scripts/color-collections/riso.ts -- <source dir> [order.json], where order.json is
// a `{ collection, order }` copied from the collection-order fixture.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GROUP_NAMES, familyOf, orderColors, orderNote, quote, savedOrder } from './order.ts';

const [source, orderFile] = process.argv.slice(2).filter((arg) => arg !== '--');
if (!source) throw new Error('usage: riso.ts <source dir> [order.json]');
const club = JSON.parse(readFileSync(join(source, 'riso-club-palettes.json'), 'utf8'));
const palettes: { name: string; colors: { hex: string }[]; issue_numbers: number[] }[] =
  club.palettes;
const order = savedOrder('riso', orderFile);

// Inks left out of the collection on request.
const excluded = new Set(['Bright Red']);
// Inks that share a value are one color, named after all of them.
const merged: { name: string; hex: string }[] = [];
for (const ink of JSON.parse(readFileSync(join(source, 'riso-palette.json'), 'utf8')) as {
  name: string;
  hex: string;
}[]) {
  if (excluded.has(ink.name)) continue;
  const same = merged.find((entry) => entry.hex.toLowerCase() === ink.hex.toLowerCase());
  if (same) same.name = `${same.name} / ${ink.name}`;
  else merged.push({ ...ink });
}
const inks = orderColors(merged, (ink) => ink.hex.toLowerCase(), order);
const counts = new Map<string, number>();
for (const palette of palettes) counts.set(palette.name, (counts.get(palette.name) ?? 0) + 1);
const used = new Set(inks.map((ink) => familyOf(ink.hex)));

const out = `import type { ColorCollection } from '../../types.js';

/**
 * Risograph inks as flat digital fills, grouped by hue family and
 * ${orderNote(order)},
 * with the ink combinations of the Riso Club issues as palettes. The ink values are the published
 * Stencil Wiki HEX values (one ink, Lime Green, from the SAIC Service Bureau), resolved on
 * ${club.retrieved_on}; the palettes are the ${palettes.length} distinct combinations of the RISOTTO Riso Club Atlas,
 * each issue's inks resolved to those values. Solid sRGB fills only: no tints, overprints or paper
 * colors. Clear Medium has no published value and is left out, and Bright Red is left out too.
 * Inks that share a value are one color named after both.
 *
 * Generated by scripts/color-collections/riso.ts.
 */
const risoInks: ColorCollection = {
  id: 'riso',
  name: 'Riso inks',
  description:
    'The risograph inks as ${inks.length} flat colors, with the ${palettes.length} ink combinations of the Riso Club issues as palettes.',
  // The ink colors come from Stencil Wiki; the palettes are RISOTTO's Riso Club combinations.
  attribution: [
    {
      name: 'Stencil Wiki',
      url: 'https://stencil.wiki/wiki/Category:Riso_inks',
      license: 'CC BY-NC-SA 4.0',
    },
    { name: 'Riso Club Atlas', url: 'https://risottostudio.com/pages/riso-club-atlas' },
  ],
  groups: [
${Object.entries(GROUP_NAMES)
  .filter(([id]) => used.has(id))
  .map(([id, name]) => `    { id: ${quote(id)}, name: ${quote(name)} },`)
  .join('\n')}
  ],
  colors: [
${inks
  .map(
    (ink) =>
      `    { value: ${quote(ink.hex.toLowerCase())}, name: ${quote(ink.name)}, group: ${quote(familyOf(ink.hex))} },`,
  )
  .join('\n')}
  ],
  palettes: [
${palettes
  .map((palette) => {
    const name =
      (counts.get(palette.name) ?? 0) > 1
        ? `${palette.name} (Issue ${palette.issue_numbers.join(', ')})`
        : palette.name;
    return `    { name: ${quote(name)}, colors: [${palette.colors.map((color) => quote(color.hex.toLowerCase())).join(', ')}] },`;
  })
  .join('\n')}
  ],
};

export default risoInks;
export { risoInks };
`;
writeFileSync('src/foundation/color-palette/collections/riso/index.ts', out);
console.log(inks.length, 'inks', palettes.length, 'palettes');
