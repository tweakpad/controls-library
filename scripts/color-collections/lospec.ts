// Generates src/foundation/color-palette/collections/lospec/index.ts from lospec-colors.json and
// lospec-palettes.json: a selection of 40 Lospec palettes and the colors they use. Each palette is
// named with its author, so the credit travels with it. Usage:
// npx vite-node scripts/color-collections/lospec.ts -- <source dir> [order.json]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GROUP_NAMES, familyOf, orderColors, orderNote, quote, savedOrder } from './order.ts';

const [source, orderFile] = process.argv.slice(2).filter((arg) => arg !== '--');
if (!source) throw new Error('usage: lospec.ts <source dir> [order.json]');
const read = (file: string) => JSON.parse(readFileSync(join(source, file), 'utf8'));
const data = read('lospec-palettes.json') as {
  retrieved: string;
  palettes: {
    name: string;
    author: { name: string } | null;
    attribution_text: string | null;
    colors: string[];
  }[];
};
const palettes = data.palettes;
const order = savedOrder('lospec', orderFile);
const colors = orderColors(
  (read('lospec-colors.json').colors as { hex: string }[]).map((color) => color.hex.toLowerCase()),
  (value) => value,
  order,
);
const listed = new Set(colors);
for (const palette of palettes)
  for (const hex of palette.colors)
    if (!listed.has(hex.toLowerCase())) throw new Error(`${palette.name}: ${hex} is not listed`);

// The author's Lospec name, or the creator a palette without an account credits ("Created by X.").
const authorOf = (palette: (typeof palettes)[number]): string | undefined =>
  palette.author?.name.trim() ||
  /^Created by ([^,.]+)/.exec(palette.attribution_text ?? '')?.[1]?.trim();
const nameOf = (palette: (typeof palettes)[number]) => {
  const author = authorOf(palette);
  return author ? `${palette.name} by ${author}` : palette.name;
};
const used = new Set(colors.map(familyOf));
const out = `import type { ColorCollection } from '../../types.js';

/**
 * A selection of ${palettes.length} pixel-art palettes from Lospec, retrieved on ${data.retrieved}, and the
 * ${colors.length} colors they use, grouped by hue family and
 * ${orderNote(order)}.
 * Each palette is named with its author; colors and their order within a palette are the
 * author's. Colors have no names on Lospec. Rights stay with each palette's author: Lospec
 * publishes no license for the palettes.
 *
 * Generated by scripts/color-collections/lospec.ts.
 */
const lospecPalettes: ColorCollection = {
  id: 'lospec',
  name: 'Lospec palettes',
  description:
    'A selection of ${palettes.length} pixel-art palettes from Lospec and the ${colors.length} colors they use, each palette named with its author.',
  attribution: [{ name: 'Lospec', url: 'https://lospec.com/palette-list' }],
  groups: [
${Object.entries(GROUP_NAMES)
  .filter(([id]) => used.has(id))
  .map(([id, name]) => `    { id: ${quote(id)}, name: ${quote(name)} },`)
  .join('\n')}
  ],
  colors: [
${colors.map((value) => `    { value: ${quote(value)}, group: ${quote(familyOf(value))} },`).join('\n')}
  ],
  palettes: [
${palettes
  .map(
    (palette) =>
      `    { name: ${quote(nameOf(palette))}, colors: [${palette.colors.map((hex) => quote(hex.toLowerCase())).join(', ')}] },`,
  )
  .join('\n')}
  ],
};

export default lospecPalettes;
export { lospecPalettes };
`;
writeFileSync('src/foundation/color-palette/collections/lospec/index.ts', out);
console.log(colors.length, 'colors', palettes.length, 'palettes');
