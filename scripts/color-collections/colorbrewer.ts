// Generates src/foundation/color-palette/collections/colorbrewer/index.ts from the ColorBrewer
// export: colorbrewer-colors.json (unique colors) and colorbrewer-palettes.json (every published
// scheme size). Usage: npx vite-node scripts/color-collections/colorbrewer.ts -- <source dir>
// [order.json], where order.json is a `{ collection, order }` copied from the collection-order
// fixture.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GROUP_NAMES, familyOf, orderColors, orderNote, quote, savedOrder } from './order.ts';

const [source, orderFile] = process.argv.slice(2).filter((arg) => arg !== '--');
if (!source) throw new Error('usage: colorbrewer.ts <source dir> [order.json]');
const colors: { hex: string }[] = JSON.parse(
  readFileSync(join(source, 'colorbrewer-colors.json'), 'utf8'),
).colors;
const palettes: { id: string; name: string; color_count: number; colors: string[] }[] = JSON.parse(
  readFileSync(join(source, 'colorbrewer-palettes.json'), 'utf8'),
).palettes;
const order = savedOrder('colorbrewer', orderFile);

const values = orderColors(
  colors.map((color) => color.hex.toLowerCase()),
  (value) => value,
  order,
);
const used = new Set(values.map(familyOf));
const out = `import type { ColorCollection } from '../../types.js';

/**
 * The ColorBrewer colors and schemes: the ${values.length} unique colors of the official export,
 * grouped by hue family and
 * ${orderNote(order)}, and every
 * published size of its sequential, diverging and qualitative schemes as palettes (${palettes.length}).
 * Colors have no names in the export. ColorBrewer is by Cynthia Brewer, Mark Harrower and The
 * Pennsylvania State University, under the Apache License 2.0 (LICENSE beside this file).
 *
 * Generated by scripts/color-collections/colorbrewer.ts.
 */
const colorBrewer: ColorCollection = {
  id: 'colorbrewer',
  name: 'ColorBrewer',
  description:
    'Cartographic color schemes by Cynthia Brewer: ${values.length} colors, with every size of the sequential, diverging and qualitative schemes as palettes.',
  attribution: [
    { name: 'ColorBrewer', url: 'https://colorbrewer2.org', license: 'Apache 2.0' },
  ],
  groups: [
${Object.entries(GROUP_NAMES)
  .filter(([id]) => used.has(id))
  .map(([id, name]) => `    { id: ${quote(id)}, name: ${quote(name)} },`)
  .join('\n')}
  ],
  colors: [
${values.map((value) => `    { value: ${quote(value)}, group: ${quote(familyOf(value))} },`).join('\n')}
  ],
  palettes: [
${palettes
  .map(
    (palette) =>
      `    { name: ${quote(`${palette.name} ${palette.color_count}`)}, colors: [${palette.colors
        .map((color) => quote(color.toLowerCase()))
        .join(', ')}] },`,
  )
  .join('\n')}
  ],
};

export default colorBrewer;
export { colorBrewer };
`;
writeFileSync('src/foundation/color-palette/collections/colorbrewer/index.ts', out);
console.log(values.length, 'colors', palettes.length, 'palettes');
