// Generates src/foundation/color-palette/collections/werner/index.ts from werner-simple.json (the
// recolorize `werner` dataset as name → HEX). The book's own families are a classification, not
// palettes, so the collection has none. Usage:
// npx vite-node scripts/color-collections/werner.ts -- <source dir> [order.json]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GROUP_NAMES, familyOf, orderColors, orderNote, quote, savedOrder } from './order.ts';

const [source, orderFile] = process.argv.slice(2).filter((arg) => arg !== '--');
if (!source) throw new Error('usage: werner.ts <source dir> [order.json]');
const entries = Object.entries(
  JSON.parse(readFileSync(join(source, 'werner-simple.json'), 'utf8')) as Record<string, string>,
);
const order = savedOrder('werner', orderFile);

// The dataset's lowercase name with its first letter capitalized: snow white → Snow white.
const colors = orderColors(
  entries.map(([name, hex]) => ({
    value: hex.toLowerCase(),
    name: name.charAt(0).toUpperCase() + name.slice(1),
  })),
  (color) => color.value,
  order,
);
const used = new Set(colors.map((color) => familyOf(color.value)));
const out = `import type { ColorCollection } from '../../types.js';

/**
 * Werner's Nomenclature of Colours (Patrick Syme's 1821 edition of Abraham Gottlob Werner's
 * scheme): ${colors.length} named colors, grouped by hue family and
 * ${orderNote(order)}.
 * Values are the recolorize \`werner\` dataset by Hannah Weller, the average colors of the scanned
 * swatches of Nicholas Rougeux's digital edition; names keep the dataset's spelling with the first
 * letter capitalized. The book's families are a classification, not palettes, so none are listed.
 * CC BY 4.0 (LICENSE beside this file).
 *
 * Generated by scripts/color-collections/werner.ts.
 */
const wernerColors: ColorCollection = {
  id: 'werner',
  name: "Werner's Nomenclature of Colours",
  description:
    "The ${colors.length} named colors of Werner's Nomenclature of Colours (1821), sampled from scans of the book.",
  attribution: [
    { name: 'recolorize', url: 'https://github.com/hiweller/recolorize', license: 'CC BY 4.0' },
    { name: 'C82', url: 'https://www.c82.net/werner/' },
  ],
  groups: [
${Object.entries(GROUP_NAMES)
  .filter(([id]) => used.has(id))
  .map(([id, name]) => `    { id: ${quote(id)}, name: ${quote(name)} },`)
  .join('\n')}
  ],
  colors: [
${colors
  .map(
    (color) =>
      `    { value: ${quote(color.value)}, name: ${quote(color.name)}, group: ${quote(familyOf(color.value))} },`,
  )
  .join('\n')}
  ],
};

export default wernerColors;
export { wernerColors };
`;
writeFileSync('src/foundation/color-palette/collections/werner/index.ts', out);
console.log(colors.length, 'colors');
