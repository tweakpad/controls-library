// Generates src/foundation/color-palette/collections/sanzo-wada/index.ts from sanzo-wada-simple.json
// (the combinations) and sanzo-wada-colors.json (the color names). Usage:
// npx vite-node scripts/color-collections/sanzo-wada.ts -- <source dir> [order.json]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GROUP_NAMES, familyOf, orderColors, orderNote, quote, savedOrder } from './order.ts';

const [source, orderFile] = process.argv.slice(2).filter((arg) => arg !== '--');
if (!source) throw new Error('usage: sanzo-wada.ts <source dir> [order.json]');
const combinations: { combination_number: number; colors: string[] }[] = JSON.parse(
  readFileSync(join(source, 'sanzo-wada-simple.json'), 'utf8'),
);
const named: { name: string; hex: string }[] = JSON.parse(
  readFileSync(join(source, 'sanzo-wada-colors.json'), 'utf8'),
).colors;
const order = savedOrder('sanzo-wada', orderFile);

const nameOf = new Map(named.map((color) => [color.hex.toLowerCase(), color.name]));
const values = [
  ...new Set(combinations.flatMap((entry) => entry.colors.map((hex) => hex.toLowerCase()))),
];
for (const value of values) if (!nameOf.has(value)) throw new Error(`no name for ${value}`);
const colors = orderColors(values, (value) => value, order);
const used = new Set(colors.map(familyOf));
const out = `import type { ColorCollection } from '../../types.js';

/**
 * Sanzo Wada's color combinations: the ${colors.length} named colors of A Dictionary of Color
 * Combinations, grouped by hue family and
 * ${orderNote(order)}, and its ${combinations.length} numbered
 * combinations of two to four colors as palettes. Values are Matt DesLauriers' sRGB conversion of
 * the printed CMYK colors, under the MIT License (LICENSE beside this file).
 *
 * Generated by scripts/color-collections/sanzo-wada.ts.
 */
const sanzoWada: ColorCollection = {
  id: 'sanzo-wada',
  name: 'Sanzo Wada',
  description:
    "Sanzo Wada's Dictionary of Color Combinations: ${colors.length} named colors and ${combinations.length} combinations of two to four colors.",
  attribution: [
    {
      name: 'Dictionary of Colour Combinations',
      url: 'https://github.com/mattdesl/dictionary-of-colour-combinations',
      license: 'MIT',
    },
  ],
  groups: [
${Object.entries(GROUP_NAMES)
  .filter(([id]) => used.has(id))
  .map(([id, name]) => `    { id: ${quote(id)}, name: ${quote(name)} },`)
  .join('\n')}
  ],
  colors: [
${colors
  .map(
    (value) =>
      `    { value: ${quote(value)}, name: ${quote(nameOf.get(value)!)}, group: ${quote(familyOf(value))} },`,
  )
  .join('\n')}
  ],
  palettes: [
${combinations
  .map(
    (entry) =>
      `    { name: ${quote(`Combination ${entry.combination_number}`)}, colors: [${entry.colors
        .map((hex) => quote(hex.toLowerCase()))
        .join(', ')}] },`,
  )
  .join('\n')}
  ],
};

export default sanzoWada;
export { sanzoWada };
`;
writeFileSync('src/foundation/color-palette/collections/sanzo-wada/index.ts', out);
console.log(colors.length, 'colors', combinations.length, 'palettes');
